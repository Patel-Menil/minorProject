import { useState } from 'react';
import { Activity, BarChart3, BadgeCheck, HeartPulse, Info, Network, Share2, SlidersHorizontal } from 'lucide-react';
import './index.css';
import GraphView from './GraphView.jsx';
import FinalModelView from './FinalModelView.jsx';
import InteractivePredict from './InteractivePredict.jsx';
import { Evaluation, Federation, Overview, Predict } from './DemoViews.jsx';

const TABS = [
  { id: 'overview', label: 'Overview', icon: Info, view: Overview },
  { id: 'predict', label: 'Predict', icon: Activity, view: Predict },
  { id: 'graph', label: 'Patient graph', icon: Share2, view: GraphView },
  { id: 'federation', label: 'Federation', icon: Network, view: Federation },
  { id: 'evaluation', label: 'Evaluation', icon: BarChart3, view: Evaluation },
  { id: 'final', label: 'Final model', icon: BadgeCheck, view: FinalModelView, final: true },
  { id: 'interactive', label: 'Interactive prediction', icon: SlidersHorizontal, view: InteractivePredict, final: true },
  { id: 'sepsis', label: 'Sepsis model', icon: HeartPulse, view: () => <FinalModelView kind="sepsis" />, final: true },
];

function App() {
  const [tab, setTab] = useState('overview');
  const current = TABS.find(t => t.id === tab);
  const View = current.view;
  return (
    <div className="shell">
      <header className="topbar">
        <div>
          <h1>Federated Multimodal Graph Learning</h1>
          <p>Early in-hospital and ICU mortality prediction · B.Tech minor project demo</p>
        </div>
        <nav className="tabs" aria-label="Demo sections">
          {TABS.map(({ id, label, icon: Icon }) => (
            <button key={id} aria-pressed={tab === id} onClick={() => setTab(id)}><Icon size={16} />{label}</button>
          ))}
        </nav>
      </header>
      {current.final ? (
        <div className="notice notice-final" role="note">
          <strong>Final-model mode · research prototype · not for clinical use.</strong> Shows only the real-data checkpoint in{' '}
          {tab === 'sepsis' || tab === 'interactive' ? 'results/minor_project_sepsis/' : 'results/minor_project_final/'}; its data source is stated below.{' '}
          {tab === 'interactive' ? 'Inputs are hypothetical scenarios typed into the form.' : 'Patients appear under masked indices only.'}
        </div>
      ) : (
        <div className="notice" role="note">
          <strong>Synthetic data · academic demonstration · not for clinical use.</strong> The patients shown are generated by
          a random process (not eICU records), and the demo model's outputs are not clinically meaningful.
        </div>
      )}
      <main className="view"><View /></main>
    </div>
  );
}

export default App;
